package events

import (
	"context"
	"errors"
	"fmt"
	"os/exec"
	"ripple/mutex"
	"ripple/utils"
	"time"
)

/**
 * ErrExitError identifies an event handler that terminated unsuccessfully.
 */
var ErrExitError = errors.New("exit error")

/**
 * ErrTimeout identifies an event dispatch or handler execution timeout.
 */
var ErrTimeout = errors.New("timed-out")

/**
 * ExecChannel is an event request submitted to the dispatcher worker.
 *
 * Each request contains the event to execute, any additional
 * arguments passed to handlers, and a completion channel used
 * to return the execution result to the caller.
 */
type ExecChannel struct {
	/*
	 * EventType is the event trigger to dispatch.
	 */
	EventType string

	/*
	 * Args contains additional arguments passed to matching handlers.
	 */
	Args []string

	/**
	 *
	 */
	Timeout time.Duration

	/*
	 * Done receives the completion error from the dispatcher worker.
	 */
	Done chan error
}

/**
 * detachedRegistry tracks detached handlers that are currently running.
 *
 * The key is the handler executable identity, which prevents the same detached
 * handler from being launched concurrently with itself.
 */
var detachedRegistry = struct {
	mutex.LockState

	Map map[FileID]struct{}
}{
	Map: make(map[FileID]struct{}),
}

/**
 * Global event dispatch queue.
 *
 * Requests submitted through DispatchEvent() are serialized
 * through this queue and processed by the dispatcher worker.
 */
var dispatchQueue chan ExecChannel

/**
 * Initializes the event dispatcher.
 *
 * A dedicated worker goroutine is created to process queued
 * dispatch requests sequentially. Each request is executed in
 * FIFO order and the resulting error is returned through the
 * request's completion channel.
 */
func InitDispatcher() {
	dispatchQueue = make(chan ExecChannel)

	go func() {
		for req := range dispatchQueue {
			req.Done <- executeEvent(
				req.EventType,
				req.Args,
				req.Timeout,
			)

			close(req.Done)
		}
	}()
}

/**
 * Dispatches an event through the global dispatcher queue.
 *
 * The request is queued for execution and processed in FIFO
 * order by the dispatcher worker. The caller blocks until the
 * event has completed synchronous execution.
 *
 * @param eventType
 *   Event identifier to dispatch.
 *
 * @param args
 *   Additional arguments passed to event handlers.
 *
 * @param timeout
 *   Maximum runtime per synchronous handler. Zero disables the timeout.
 *
 * @return
 *   Any execution error returned by an event handler.
 */
func DispatchEvent(
	eventType string,
	args []string,
	timeout time.Duration,
) error {
	done := make(chan error, 1)

	dispatchQueue <- ExecChannel{
		EventType: eventType,
		Args:      args,
		Timeout:   timeout,
		Done:      done,
	}

	return <-done
}

/**
 * Executes a single event handler.
 *
 * The handler is launched through systemd-cat to integrate its
 * output with the system journal using the supplied identifier.
 *
 * @param eventType
 *   Event identifier being dispatched.
 *
 * @param event
 *   Event handler definition to execute.
 *
 * @param args
 *   Additional arguments passed to the handler.
 *
 * @param identifier
 *   Journal identifier used for log messages generated by the
 *   handler process.
 *
 * @return
 *   Nil on successful execution, or a Ripple error that preserves the handler
 *   process exit code when available.
 */
func executeEventHandler(
	eventType string,
	event *EventHandler,
	args []string,
	identifier string,
	timeout time.Duration,
) error {
	cmdArgs := append(
		[]string{
			"--stderr-priority=err",
			"--identifier=" + identifier,
			"--",
			event.Path,
			eventType,
		},
		args...,
	)

	var cmd *exec.Cmd
	ctx := context.Background()

	if timeout > 0 {
		var cancel context.CancelFunc
		ctx, cancel = context.WithTimeout(ctx, timeout)
		defer cancel()

		cmd = exec.CommandContext(
			ctx,
			"systemd-cat",
			cmdArgs...,
		)

	} else {
		cmd = exec.Command(
			"systemd-cat",
			cmdArgs...,
		)
	}

	err := cmd.Run()

	if err != nil {
		if errors.Is(ctx.Err(), context.DeadlineExceeded) {
			return fmt.Errorf("%w: handler %s exceeded its execution timeout", ErrTimeout, event.Name)

		} else if exitErr, ok := err.(*exec.ExitError); ok {
			return fmt.Errorf("%w: %s", ErrExitError, exitErr.Error())
		}

		return err
	}

	return nil
}

/**
 * Executes an event to all registered handlers.
 *
 * Handlers marked as detached are executed in separate goroutines
 * and are prevented from running concurrently with themselves. If a detached
 * handler is already running, dispatch for that event stops without error.
 *
 * Non-detached handlers are executed synchronously in the current
 * goroutine and any execution error is returned to the caller.
 *
 * @param eventType
 *   Event identifier to dispatch.
 *
 * @param args
 *   Additional arguments passed to each event handler.
 *
 * @return
 *   An execution error from a synchronous handler, if any.
 */
func executeEvent(
	eventType string,
	args []string,
	timeout time.Duration,
) error {
	handlers := ListHandlers(eventType)

	var ret error

	for _, handler := range handlers {
		if handler.Detached {
			if !tryLockEventHandler(handler.ID) {
				return nil
			}

			go func() {
				defer unlockEventHandler(handler.ID)

				identifier := fmt.Sprintf(
					"ripple.%s#%d",
					eventType,
					handler.ID.Ino,
				)

				utils.Println("executing %s in detached thread (%s)", handler.Name, identifier)

				err := executeEventHandler(
					eventType,
					handler,
					args,
					identifier,
					0,
				)

				if err != nil {
					utils.EPrintln(err)
				}
			}()

			continue
		}

		identifier := fmt.Sprintf(
			"ripple.%s",
			eventType,
		)

		utils.Println("executing %s in main thread (%s)", handler.Name, identifier)

		err := executeEventHandler(
			eventType,
			handler,
			args,
			identifier,
			timeout,
		)

		if err != nil {
			ret = err
		}
	}

	return ret
}

/**
 * Attempts to acquire an execution lock for a detached handler.
 *
 * If the handler is already running, the lock request fails and
 * false is returned.
 *
 * @param id
 *   Unique identifier of the event handler.
 *
 * @return
 *   True if the lock was acquired, otherwise false.
 */
func tryLockEventHandler(id FileID) bool {
	var exists bool

	mutex.Synchronized(&detachedRegistry, func() {
		_, exists = detachedRegistry.Map[id]

		if !exists {
			detachedRegistry.Map[id] = struct{}{}
		}
	})

	return !exists
}

/**
 * Releases a previously acquired detached handler lock.
 *
 * @param id
 *   Unique identifier of the event handler.
 */
func unlockEventHandler(id FileID) {
	mutex.Synchronized(&detachedRegistry, func() {
		delete(detachedRegistry.Map, id)
	})
}
